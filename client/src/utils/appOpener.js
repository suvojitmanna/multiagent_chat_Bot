export const detectAppOrWebsite = (text) => {
  if (!text || typeof text !== "string") return null;
  const trimmed = text.trim();
  const directUrlMatch = trimmed.match(/^(?:https?:\/\/[^\s]+|www\.[^\s]+|[a-zA-Z0-9-]+\.(?:com|org|net|io|ai|dev|app|co|in|edu|gov|xyz|info|biz|me|live|online|tv|tech|cc)[^\s]*)$/i);
  if (directUrlMatch) {
    let url = directUrlMatch[0];
    if (!url.startsWith("http://") && !url.startsWith("https://")) {
      url = "https://" + url;
    }
    return {
      name: directUrlMatch[0].replace(/^https?:\/\//, "").replace(/^www\./, "").split("/")[0],
      url,
      isPureCommand: true,
      category: "Website",
    };
  }
  const openIntentRegex = /^(?:please\s+|can\s+you\s+|could\s+you\s+|would\s+you\s+|hey\s+)?(?:open|launch|visit|go\s+to|start|browse|run)\s+(?:the\s+)?(?:app\s+|website\s+|site\s+|web\s+)?([a-zA-Z0-9.\-_:/ ]+?)(?:\s+(?:app|website|site|please|karo|koro|now))?$/i;
  const match = trimmed.match(openIntentRegex);

  if (match) {
    const rawTarget = match[1].trim().toLowerCase().replace(/^(the\s+)/, "");
    const normalizedKey = rawTarget.replace(/[\s.-]/g, "").replace(/\.com$/, "");

    if (APP_REGISTRY[normalizedKey]) {
      return {
        ...APP_REGISTRY[normalizedKey],
        isPureCommand: true,
      };
    }

    const foundEntry = Object.values(APP_REGISTRY).find(
      (entry) => entry.name.toLowerCase() === rawTarget.toLowerCase()
    );
    if (foundEntry) {
      return {
        ...foundEntry,
        isPureCommand: true,
      };
    }
    if (rawTarget.includes(".")) {
      let url = rawTarget;
      if (!url.startsWith("http://") && !url.startsWith("https://")) {
        url = "https://" + url;
      }
      return {
        name: rawTarget.replace(/^https?:\/\//, "").replace(/^www\./, "").split("/")[0],
        url,
        isPureCommand: true,
        category: "Website",
      };
    }

    const cleanWord = rawTarget.split(/\s+/)[0];
    if (cleanWord && /^[a-z0-9-]+$/.test(cleanWord)) {
      const capitalized = cleanWord.charAt(0).toUpperCase() + cleanWord.slice(1);
      return {
        name: capitalized,
        url: `https://www.${cleanWord}.com`,
        isPureCommand: true,
        category: "Website",
      };
    }
  }

  const compoundRegex = /^(?:please\s+|can\s+you\s+)?(?:open|launch|visit|go\s+to)\s+(?:the\s+)?([a-zA-Z0-9.\-]+)\s+(?:and|to|then)\s+(.+)$/i;
  const compoundMatch = trimmed.match(compoundRegex);
  if (compoundMatch) {
    const targetWord = compoundMatch[1].trim().toLowerCase().replace(/\.com$/, "");
    const remainder = compoundMatch[2].trim();
    const appEntry = APP_REGISTRY[targetWord];

    if (appEntry) {
      return {
        ...appEntry,
        isPureCommand: false,
        queryRemainder: remainder,
      };
    }

    if (targetWord.includes(".")) {
      let url = targetWord;
      if (!url.startsWith("http://") && !url.startsWith("https://")) {
        url = "https://" + url;
      }
      return {
        name: targetWord,
        url,
        isPureCommand: false,
        queryRemainder: remainder,
      };
    }
  }

  return null;
};
